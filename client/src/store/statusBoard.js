const SB_KEY = 'tracs.catcc.sb'

function serialize(s) {
  return {
    event: s.event, launch: s.launch, recovery: s.recovery,
    clg: s.clg, vis: s.vis, qnh: s.qnh,
    caseLaunch: s.caseLaunch, caseRecovery: s.caseRecovery, cvApp: s.cvApp,
    marBtn: s.marBtn, app: s.app, twrBtn: s.twrBtn, depBtn: s.depBtn,
    rad: s.rad, radAuto: s.radAuto,
    entries: s.entries, nextId: s.nextId,
  }
}

function loadSaved() {
  try { return JSON.parse(localStorage.getItem(SB_KEY) ?? 'null') } catch { return null }
}

const saved = loadSaved() ?? {}

// entry.auto marks the fields the board filled itself ({ eat: true }), which
// show green until a user types over them.
function withoutAuto(auto, field) {
  if (!auto?.[field]) return auto
  const { [field]: _, ...rest } = auto
  return rest
}

export const useStatusBoardStore = create((set) => ({
  event:        saved.event        ?? '',
  launch:       saved.launch       ?? '',
  recovery:     saved.recovery     ?? '',
  clg:          saved.clg          ?? '',
  vis:          saved.vis          ?? '',
  qnh:          saved.qnh          ?? '',
  caseLaunch:   saved.caseLaunch   ?? '',
  caseRecovery: saved.caseRecovery ?? '',
  cvApp:        saved.cvApp        ?? '',
  marBtn:       saved.marBtn       ?? '',
  app:          saved.app          ?? '',
  twrBtn:       saved.twrBtn       ?? '',
  depBtn:       saved.depBtn       ?? '',
  rad:          saved.rad          ?? '',
  radAuto:      saved.radAuto      ?? false,
  entries:      saved.entries      ?? [],
  nextId:       saved.nextId       ?? 1,
  // The row whose DME/ANGELS the scope status text shows. This window's own
  // choice: kept out of serialize(), so never saved or sent to other controllers.
  focusId:      null,

  setHeader: (field, value) => set({ [field]: value }),

  // RAD as typed (auto false), or as worked out by the board (auto true, green).
  setRad: (rad, auto = false) => set({ rad, radAuto: auto && !!rad }),

  // An approach radial as typed, or an E/H radial worked out at entry (mode 'E'/'H').
  setAppRad: (id, appRad, mode = '') =>
    set((s) => ({
      entries: s.entries.map((e) => e.id === id
        ? { ...e, appRad, radMode: appRad ? mode : '', auto: withoutAuto(e.auto, 'appRad') }
        : e),
    })),

  addEntry: (callsign = '', unitId = null) =>
    set((s) => {
      if (callsign && s.entries.some((e) => e.callsign === callsign)) return s
      return {
        entries: [...s.entries, {
          id: s.nextId, evt: '', callsign, unitId,
          sideNumber: '', bcn: '', pilot: '', type: '', msn: '', atd: '', radial: '', bingo: '', appRad: '', eat: '', btn: '', dme: '', angels: '', state: '', ata: '',
        }],
        nextId: s.nextId + 1,
      }
    }),

  addMissionEntries: (incoming) =>
    set((s) => {
      const existing = new Set(s.entries.map(e => e.callsign).filter(Boolean))
      const toAdd = []
      let id = s.nextId
      for (const e of incoming) {
        if (e.callsign && existing.has(e.callsign)) continue
        toAdd.push({
          id, fromMission: true,
          evt: '', callsign: e.callsign, unitId: null,
          sideNumber: e.modex, bcn: '', pilot: '', type: e.type, msn: e.task,
          atd: '', radial: '', bingo: '', appRad: '', eat: '', btn: '', dme: '', angels: '', state: '', ata: '',
        })
        id++
      }
      return { entries: [...s.entries, ...toAdd], nextId: id }
    }),

  clearMissionData: () =>
    set((s) => ({
      clg: '', vis: '', qnh: '',
      entries: s.entries.filter(e => !e.fromMission),
    })),

  // A user edit makes the field theirs: it drops out of the row's autogenerated set.
  updateEntry: (id, field, value) =>
    set((s) => {
      if (field === 'callsign' && value && s.entries.some((e) => e.id !== id && e.callsign === value)) return s
      return { entries: s.entries.map((e) => e.id === id ? { ...e, [field]: value, auto: withoutAuto(e.auto, field) } : e) }
    }),

  // A command-line row entry (modules/catcc/boardLine.js): row id, or a new
  // row starting from init, with every given field applied in one update.
  // DME and ANG typed together stay linked if they agree, and are kept as
  // typed (unlinked) if not.
  applyEntryLine: (id, init, fields) =>
    set((s) => {
      const { appRad, dme, angels, ...plain } = fields
      let { entries, nextId } = s
      let entry = id != null ? entries.find((e) => e.id === id) : null
      if (!entry) {
        entry = { id: nextId, fromMission: false, evt: '', callsign: '', unitId: null, sideNumber: '', bcn: '', pilot: '', type: '', msn: '', atd: '', radial: '', bingo: '', appRad: '', eat: '', btn: '', dme: '', angels: '', state: '', ata: '', ...init }
        entries = [...entries, entry]
        nextId++
      }
      let next = { ...entry, ...plain }
      for (const field of Object.keys(plain)) next.auto = withoutAuto(next.auto, field)
      if (appRad !== undefined) next = { ...next, appRad, radMode: '', auto: withoutAuto(next.auto, 'appRad') }
      if (dme !== undefined && angels !== undefined) {
        const linked = stackFieldsFor(next, 'dme', dme)
        next = { ...next, ...(dme && !linked.unlinked && linked.angels === angels ? linked : { dme, angels, unlinked: !!(dme || angels) }) }
      } else if (dme !== undefined) {
        next = { ...next, ...stackFieldsFor(next, 'dme', dme) }
      } else if (angels !== undefined) {
        next = { ...next, ...stackFieldsFor(next, 'angels', angels) }
      }
      return { entries: entries.map((e) => e.id === entry.id ? next : e), nextId }
    }),

  // DME and ANGELS are one linked pair (see stackFieldsFor).
  setStackValue: (id, field, typed) =>
    set((s) => ({ entries: s.entries.map((e) => e.id === id ? { ...e, ...stackFieldsFor(e, field, typed) } : e) })),

  // Autofill stamps (see modules/catcc/StatusBoardAutofill.jsx). A new
  // launch starts a new cycle, so it blanks the previous ATA in the same set.
  stampDeparture: (id, hhmm) =>
    set((s) => ({ entries: s.entries.map((e) => e.id === id ? { ...e, atd: hhmm, ata: '' } : e) })),

  stampArrival: (id, hhmm) =>
    set((s) => ({ entries: s.entries.map((e) => e.id === id ? { ...e, ata: hhmm } : e) })),

  // CASE 2/3 marshal: the next EAT after the latest in the stack, and the lowest
  // free altitude that keeps the stack climbing (see fitStackAngels).
  assignNextMarshal: (id, defaultRad) =>
    set((s) => {
      if (s.caseRecovery !== '2' && s.caseRecovery !== '3') return s
      const entry = s.entries.find((e) => e.id === id)
      if (!entry || entry.angels || entry.dme) return s
      // A row that already has an EAT keeps it. The altitude must keep the
      // stack climbing; with none free between its neighbours the row is left
      // for the controller (the board shows it red).
      const eat    = entry.eat || nextStackEat(s.entries, id)
      const angels = eat ? fitStackAngels(s.entries, id, eat, defaultRad) : null
      if (angels == null) return s
      // The row keeps the radial it was given now, even if the header RAD changes later
      const radial = !entry.appRad && defaultRad ? { appRad: defaultRad, radMode: '' } : {}
      const auto = { ...entry.auto, ...(entry.eat ? {} : { eat: true }), ...(radial.appRad ? { appRad: true } : {}) }
      return {
        entries: s.entries.map((e) => e.id === id
          ? { ...e, ...stackFieldsFor(e, 'angels', String(angels)), ...(entry.eat ? {} : { eat }), ...radial, auto }
          : e),
      }
    }),

  // Clear the approach side of these rows (the green SIDE's right-click
  // menu). Blank RAD and BTN fall back to the header values.
  clearApproach: (ids) =>
    set((s) => {
      const clear = new Set(ids)
      return {
        entries: s.entries.map((e) => clear.has(e.id)
          ? {
              ...e, appRad: '', radMode: '', dme: '', angels: '', unlinked: false,
              eat: '', btn: '', state: '', ata: '',
              auto: withoutAuto(withoutAuto(e.auto, 'eat'), 'appRad'),
            }
          : e),
      }
    }),

  insertEntryAfter: (afterId) =>
    set((s) => {
      const newEntry = { id: s.nextId, fromMission: false, evt: '', callsign: '', unitId: null, sideNumber: '', bcn: '', pilot: '', type: '', msn: '', atd: '', radial: '', bingo: '', appRad: '', eat: '', btn: '', dme: '', angels: '', state: '', ata: '' }
      const idx = s.entries.findIndex((e) => e.id === afterId)
      const entries = idx === -1
        ? [...s.entries, newEntry]
        : [...s.entries.slice(0, idx + 1), newEntry, ...s.entries.slice(idx + 1)]
      return { entries, nextId: s.nextId + 1 }
    }),

  recycleBcn: (id) =>
    set((s) => ({
      entries: s.entries.map((e) =>
        e.id === id ? { ...e, bcn: generateBcn(s.entries.map((e2) => e2.bcn)) } : e
      ),
    })),

  renameEntry: (unitId, newCallsign) =>
    set((s) => ({
      entries: s.entries.map((e) =>
        String(e.unitId) === String(unitId) ? { ...e, callsign: newCallsign } : e
      ),
    })),

  // Clear one column on these rows, as Delete would in each cell: a linked
  // DME/ANG pair clears together, and RAD/BTN fall back to the header.
  clearColumn: (ids, field) =>
    set((s) => {
      const clear = new Set(ids)
      return {
        entries: s.entries.map((e) => {
          if (!clear.has(e.id)) return e
          const fields = (field === 'dme' || field === 'angels') ? stackFieldsFor(e, field, '')
                       : field === 'appRad' ? { appRad: '', radMode: '' }
                       : { [field]: '' }
          return { ...e, ...fields, auto: withoutAuto(e.auto, field) }
        }),
      }
    }),

  removeEntries: (ids) =>
    set((s) => {
      const gone = new Set(ids)
      return { entries: s.entries.filter((e) => !gone.has(e.id)), focusId: gone.has(s.focusId) ? null : s.focusId }
    }),

  removeEntry: (id) =>
    set((s) => ({ entries: s.entries.filter((e) => e.id !== id), focusId: s.focusId === id ? null : s.focusId })),

  toggleFocus: (id) => set((s) => ({ focusId: s.focusId === id ? null : id })),
  clearFocus:  () => set({ focusId: null }),

  moveEntry: (id, dir) =>
    set((s) => {
      const idx = s.entries.findIndex((e) => e.id === id)
      const next = idx + dir
      if (next < 0 || next >= s.entries.length) return s
      const entries = [...s.entries]
      ;[entries[idx], entries[next]] = [entries[next], entries[idx]]
      return { entries }
    }),

  reset: () => set({
    event: '', launch: '', recovery: '',
    clg: '', vis: '', qnh: '',
    caseLaunch: '', caseRecovery: '', cvApp: '', marBtn: '', app: '', twrBtn: '', depBtn: '',
    rad: '', radAuto: false,
    entries: [], nextId: 1,
  }),

  clearAll: () => set({
    event: '', launch: '', recovery: '',
    clg: '', vis: '', qnh: '',
    caseLaunch: '', caseRecovery: '', cvApp: '', marBtn: '', app: '', twrBtn: '', depBtn: '',
    rad: '', radAuto: false,
    entries: [], nextId: 1,
  }),
}))

// ── Persistence + cross-window sync ──────────────────────────────────────────
// A popped-out board has no WebRTC client: its main window carries its edits
// to the network and carries remote edits back to it. _applying records where
// the change being applied came from, so the subscriber forwards it everywhere
// except back to its source:
//   null      a local edit: localStorage, WebRTC and the channel
//   'remote'  another controller (WebRTC apply or callsign rename): localStorage + channel
//   'popup'   this position's pop-out: localStorage + WebRTC
//   'window'  another main window of this position: localStorage only (it sent it itself)
// Deliberately NOT utils/storeSync.js's syncStore — that helper's isSyncing flag
// is private to its own subscribe/onmessage closure, with no way for external
// callers to mark an apply's source.
let _applying = null

const _params  = new URLSearchParams(window.location.search)
const _isPopup = !!_params.get('window')

// WebRTC broadcast hook — registered by the WebRTC client after sign-in.
const { register: registerStatusBoardBroadcast, broadcast: _webrtcBroadcast } = createBroadcastHook()
export { registerStatusBoardBroadcast }

// The wire shape for STATUS_BOARD_UPDATE, also used for the status board part
// of a CATCC state dump, so live updates and late-join dumps carry the same fields.
export function buildStatusBoardPayload(s) {
  return {
    eventHeader: {
      event: s.event, launch: s.launch, recovery: s.recovery,
      clg: s.clg, vis: s.vis, qnh: s.qnh,
    },
    recoveryStatus: {
      caseLaunch: s.caseLaunch, caseRecovery: s.caseRecovery, cvApp: s.cvApp,
      app: s.app, marBtn: s.marBtn, twrBtn: s.twrBtn, depBtn: s.depBtn,
      rad: s.rad, radAuto: s.radAuto,
    },
    entries: s.entries,
  }
}

// Rows from other controllers come from their own counters, and the wire
// payload carries no nextId, so a new local row must start past every id
// already on the board. Never moves backwards.
function nextFreeId(entries, nextId) {
  return entries.reduce((n, e) => (Number.isFinite(e.id) && e.id >= n ? e.id + 1 : n), nextId)
}

function applyFrom(source, patch) {
  _applying = source
  try {
    useStatusBoardStore.setState(patch)
  } finally {
    _applying = null
  }
}

// Scoped to this position's own windows, like store/strips.js: two positions
// signed in from one app instance (Electron's New Window) each keep their own board.
let _sbCh = null
const _sbChannelName = (facilityId, positionName) => `tracs-statusboard-${facilityId}-${positionName}`

function _setupSbChannel(facilityId, positionName) {
  _sbCh?.close()
  _sbCh = new BroadcastChannel(_sbChannelName(facilityId, positionName))
  _sbCh.onmessage = (e) => {
    if (e.data?.type === 'STATE_UPDATE') {
      const { state } = e.data
      const entries = state.entries ?? useStatusBoardStore.getState().entries
      applyFrom(e.data.relay ? 'popup' : 'window', {
        ...state,
        nextId: nextFreeId(entries, Math.max(state.nextId ?? 1, useStatusBoardStore.getState().nextId)),
      })
    } else if (e.data?.type === 'FOCUS') {
      applyFrom('window', { focusId: e.data.id })
    } else if (e.data?.type === 'REQUEST_STATE') {
      // A reply is never a relay request: opening a second pop-out mustn't
      // make the main window resend the board to everyone.
      const s = useStatusBoardStore.getState()
      _sbCh.postMessage({ type: 'STATE_UPDATE', state: serialize(s) })
      _sbCh.postMessage({ type: 'FOCUS', id: s.focusId })
    }
  }
  _sbCh.postMessage({ type: 'REQUEST_STATE' })
}

useStatusBoardStore.subscribe((state, prev) => {
  // The focused row only travels between this position's own windows (a
  // double-click in the pop-out drives the main window's status text).
  if (state.focusId !== prev.focusId && !_applying) _sbCh?.postMessage({ type: 'FOCUS', id: state.focusId })
  if (shallowEqual(serialize(state), serialize(prev))) return
  try { localStorage.setItem(SB_KEY, JSON.stringify(serialize(state))) } catch {}
  if (_applying === 'window') return
  if (_applying !== 'remote') _webrtcBroadcast?.(buildStatusBoardPayload(state))
  if (_applying === 'popup') return
  _sbCh?.postMessage({ type: 'STATE_UPDATE', state: serialize(state), relay: _isPopup })
})

if (_isPopup) {
  // A pop-out knows its owning position from the URL it was opened with
  // (App.jsx's undock handlers).
  _setupSbChannel(_params.get('facilityId') ?? '', _params.get('positionName') ?? '')
} else {
  // A main window only knows its position after login, and may sign into a
  // different one later without restarting.
  let _lastKey = null
  const _trySetup = () => {
    const { facilityId, positionName } = useSessionStore.getState()
    if (!facilityId || !positionName) return
    const key = _sbChannelName(facilityId, positionName)
    if (key === _lastKey) return
    _lastKey = key
    _setupSbChannel(facilityId, positionName)
  }
  useSessionStore.subscribe(_trySetup)
  _trySetup()
}

// Update a status board entry's callsign by unitId without sending it over
// WebRTC: every peer applies the same CALLSIGN_RENAME itself.
export function renameStatusBoardEntry(unitId, newCallsign) {
  _applying = 'remote'
  try {
    useStatusBoardStore.getState().renameEntry(unitId, newCallsign)
  } finally {
    _applying = null
  }
}

// Apply an incoming STATUS_BOARD_UPDATE payload without sending it back out
// over WebRTC. One setState, so a pop-out never sees a new header with old rows.
export function applyStatusBoardUpdate(payload) {
  const patch = { ...(payload.eventHeader ?? {}), ...(payload.recoveryStatus ?? {}) }
  if (payload.entries != null) {
    patch.entries = payload.entries
    patch.nextId  = nextFreeId(payload.entries, useStatusBoardStore.getState().nextId)
  }
  if (Object.keys(patch).length > 0) applyFrom('remote', patch)
}
