const GLYPH_W = 5
const GLYPH_H = 7
const ADVANCE = GLYPH_W + 1 // 1px letter-spacing before scaling

function measureText(text, scale) {
  const len = text.length
  return len === 0 ? 0 : len * ADVANCE * scale - scale
}

// Draws opaque text; blendPixel comes from rasterCore so glyph pixels
// composite the same way every other layer in these build scripts does.
function drawText(buf, width, height, x0, y0, text, scale, r, g, b, a, blendPixel) {
  let cx = x0
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch] || GLYPHS[' ']
    for (let row = 0; row < GLYPH_H; row++) {
      const bits = glyph[row]
      for (let col = 0; col < GLYPH_W; col++) {
        if (bits[col] !== '#') continue
        const px0 = cx + col * scale
        const py0 = y0 + row * scale
        for (let dy = 0; dy < scale; dy++) {
          const py = py0 + dy
          if (py < 0 || py >= height) continue
          for (let dx = 0; dx < scale; dx++) {
            const px = px0 + dx
            if (px < 0 || px >= width) continue
            blendPixel(buf, (py * width + px) * 4, r, g, b, a)
          }
        }
      }
    }
    cx += ADVANCE * scale
  }
  return cx
}

module.exports = { drawText, measureText, GLYPH_W, GLYPH_H }
